def _resolve_placeholders(text: str, definitions: dict[str, str]) -> str:
    for key, value in definitions.items():
        text = text.replace(f"@{key}@", value)
    return text


def _option_prefix(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    start = text.find("  options:\n")
    pages = text.find("    pages:\n", start)
    if start == -1 or pages == -1:
        return ""
    return _dedent_yaml_block(text[start + len("  options:\n"):pages])


def _page_blocks(path: Path) -> tuple[str, ...]:
    text = path.read_text(encoding="utf-8")
    pages = text.find("    pages:\n")
    if pages == -1:
        return ()
    body_start = text.find("\n      - ", pages)
    end = text.find("\n...", body_start)
    if body_start == -1:
        return ()
    if end == -1:
        end = len(text)
    body = text[body_start:end]
    starts = [m.start() for m in re.finditer(r"\n      - ", body)]
    blocks: list[str] = []
    for index, start in enumerate(starts):
        block_end = starts[index + 1] if index + 1 < len(starts) else len(body)
        blocks.append(_dedent_yaml_block(body[start:block_end]))
    return tuple(blocks)


def _dedent_yaml_block(text: str) -> str:
    lines = text.strip("\n").splitlines()
    indents = [len(line) - len(line.lstrip(" ")) for line in lines if line.strip()]
    if not indents:
        return ""
    width = min(indents)
    return "\n".join(line[width:] if len(line) >= width else line for line in lines).rstrip()


def _replace_yaml_option(text: str, key: str, value: str) -> str:
    pattern = re.compile(rf"^(\s*{re.escape(key)}:\s*).*$", re.MULTILINE)
    quoted = "'" + value.replace("'", "''") + "'"
    if pattern.search(text):
        return pattern.sub(rf"\1{quoted}", text, count=1)
    return text.rstrip() + f"\n{key}: {quoted}\n"


def _indent(text: str, prefix: str) -> str:
    return "\n".join(prefix + line if line else line for line in text.splitlines())


def _slug(value: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9]+", "-", value.strip().lower()).strip("-")
    return slug or "page"


def _posix_path(path: Path) -> str:
    return path.as_posix()

def _copy_source_outline(writer: Any, reader: Any, parent: Any, page_offset: int) -> int:
    try:
        outline = reader.outline
    except Exception:
        return 0
    return _copy_outline_items(writer, reader, outline, parent, page_offset)


def _copy_outline_items(writer: Any, reader: Any, outline: Any, parent: Any, page_offset: int) -> int:
    copied = 0
    last_parent = parent
    for entry in outline or []:
        if isinstance(entry, list):
            copied += _copy_outline_items(writer, reader, entry, last_parent, page_offset)
            continue
        try:
            source_page = reader.get_destination_page_number(entry)
        except Exception:
            continue
        if source_page < 0:
            continue
        title = str(getattr(entry, "title", "") or "Sheet")
        try:
            last_parent = writer.add_outline_item(title, page_offset + source_page, parent=parent)
        except Exception:
            continue
        copied += 1
    return copied


def _discover_inputs(root: Path, output_path: Path) -> list[CombinedPdfInput]:
    native = _native_combined_source_pdfs(root)
    if native:
        schematic = _first_pdf("Schematic", root / "Schematic", output_path)
        return ([schematic] if schematic is not None else []) + native
    return [
        item
        for item in (
            _first_pdf("Schematic", root / "Schematic", output_path),
            _first_pdf("Assembly", root / "Manufacturing" / "Assembly", output_path),
            _first_pdf("Fabrication", root / "Manufacturing" / "Fabrication", output_path),
        )
        if item is not None
    ]


def _native_combined_source_pdfs(root: Path) -> list[CombinedPdfInput]:
    directory = root / COMBINED_NATIVE_DIR
    if not directory.is_dir():
        return []
    selected: dict[int, Path] = {}
    unnumbered: list[Path] = []
    for path in sorted(directory.glob("*.pdf")):
        number = _combined_source_number(path.stem)
        if number is None:
            unnumbered.append(path)
            continue
        existing = selected.get(number)
        if existing is None or _numbered_pdf_page(existing):
            selected[number] = path
    inputs = [
        CombinedPdfInput(_title_from_combined_source_name(path.stem), path)
        for _number, path in sorted(selected.items())
    ]
    inputs.extend(CombinedPdfInput(_title_from_combined_source_name(path.stem), path) for path in unnumbered)
    return inputs


def _combined_source_number(stem: str) -> int | None:
    match = re.match(r".*combined-(\d+)-", stem)
    if not match:
        return None
    try:
        return int(match.group(1))
    except ValueError:
        return None


def _title_from_combined_source_name(stem: str) -> str:
    stem = re.sub(r"-\d+$", "", stem)
    match = re.match(r".*combined-(\d+)-(.+)$", stem)
    if not match:
        return stem
    return match.group(2).replace("-", " ").upper()


def _combined_sheets(root: Path) -> list[CombinedSheet]:
    sheets: list[CombinedSheet] = []
    for index, title in enumerate(_schematic_titles(root), start=1):
        sheets.append(CombinedSheet(len(sheets) + 1, "Schematic", title, "schematic", index))
    for section, kind, yaml_name in (
        ("Assembly", "assembly", "kibot_out_pdf_assembly.yaml"),
        ("Fabrication", "fabrication", "kibot_out_pdf_fabrication.yaml"),
    ):
        for local_index, title in enumerate(_titles_from_kibot_pages(root / "boardwright_resources" / "kibot" / "yaml" / yaml_name), start=1):
            sheets.append(CombinedSheet(len(sheets) + 1, section, title, kind, local_index))
    return sheets


def _schematic_titles(root: Path) -> tuple[str, ...]:
    titles = collect_actual_sheet_titles(root, max_titles=MAX_COMBINED_TOC_ENTRIES)
    trimmed = list(titles)
    while trimmed and set(trimmed[-1]) == {"."}:
        trimmed.pop()
    return tuple(trimmed or titles[:1])


def _first_pdf(title: str, directory: Path, output_path: Path) -> CombinedPdfInput | None:
    if not directory.is_dir():
        return None
    candidates = [
        path
        for path in sorted(directory.glob("*.pdf"))
        if path.resolve() != output_path.resolve() and not _numbered_pdf_page(path)
    ]
    if not candidates:
        return None
    preferred = [path for path in candidates if title.lower() in path.stem.lower()]
    selected = preferred[0] if preferred else candidates[0]
    return CombinedPdfInput(title, selected)


def _titles_for_input(root: Path, item: CombinedPdfInput, page_count: int) -> tuple[str, ...]:
    if item.title == "Schematic":
        titles = collect_actual_sheet_titles(root, max_titles=max(page_count, 1))
    elif item.title == "Assembly":
        titles = _titles_from_kibot_pages(root / "boardwright_resources" / "kibot" / "yaml" / "kibot_out_pdf_assembly.yaml")
    elif item.title == "Fabrication":
        titles = _titles_from_kibot_pages(root / "boardwright_resources" / "kibot" / "yaml" / "kibot_out_pdf_fabrication.yaml")
    else:
        titles = (item.title,)
    return tuple(title for title in titles if title)


def _titles_from_kibot_pages(path: Path) -> tuple[str, ...]:
    if not path.is_file():
        return ()
    titles: list[str] = []
    in_pages = False
    page_indent: int | None = None
    for raw_line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if re.match(r"^\s{4}pages:\s*$", raw_line):
            in_pages = True
            page_indent = None
            continue
        if not in_pages:
            continue
        stripped = raw_line.strip()
        indent = len(raw_line) - len(raw_line.lstrip(" "))
        if page_indent is None and stripped.startswith("- "):
            page_indent = indent
        elif page_indent is not None and indent <= page_indent and stripped and not stripped.startswith("- "):
            break
        match = re.match(r"(?:-\s*)?title:\s*['\"]?(.*?)['\"]?\s*$", stripped)
        if match:
            title = match.group(1).strip()
            if title and "@" not in title and "%" not in title:
                titles.append(title)
    return tuple(titles)


def _page_title(section: str, titles: tuple[str, ...], index: int) -> str:
    if index < len(titles):
        return titles[index]
    return f"{section} {index + 1}"


def _numbered_pdf_page(path: Path) -> bool:
    stem = path.stem
    head, sep, tail = stem.rpartition("-")
    return bool(head and sep and tail.isdigit())


def _read_env(path: Path) -> dict[str, str]:
    if not path.is_file():
        return {}
    values: dict[str, str] = {}
    for raw_line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        key, sep, value = line.partition("=")
        if sep:
            values[key] = value
    return values


def _read_combined_sheet_manifest(root: Path) -> tuple[CombinedSheet, ...]:
    values = _read_env(root / COMBINED_SHEET_TITLES)
    total = read_combined_sheet_total(root)
    if not total:
        return ()
    sheets: list[CombinedSheet] = []
    for number in range(1, total + 1):
        title = values.get(f"SHEET_NAME_{number}")
        if not title:
            return ()
        section = values.get(f"SHEET_SECTION_{number}", "")
        source_kind = values.get(f"SHEET_SOURCE_KIND_{number}", "")
        try:
            source_page = int(values.get(f"SHEET_SOURCE_PAGE_{number}", "1"))
        except ValueError:
            source_page = 1
        sheets.append(CombinedSheet(number, section, title, source_kind, source_page))
    return tuple(sheets)


def _as_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in {"1", "true", "yes", "on"}


def _display_path(path: Path, root: Path) -> str:
    try:
        return str(path.resolve().relative_to(root.resolve()))
    except ValueError:
        return str(path)
