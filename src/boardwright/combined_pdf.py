def _write_native_pcb_outputs(root: Path, manifest: CombinedSheetManifest) -> tuple[list[str], list[Path]]:
    sheets = native_pcb_sheets(manifest)
    yaml_path = root / COMBINED_NATIVE_YAML
    worksheet_dir = root / GENERATED_WORKSHEETS
    worksheet_dir.mkdir(parents=True, exist_ok=True)
    yaml_path.parent.mkdir(parents=True, exist_ok=True)

    if not sheets:
        yaml_path.write_text("kibot:\n  version: 1\n\noutputs: []\n", encoding="utf-8", newline="\n")
        return [], []

    definitions = _main_definitions(root)
    source_worksheets = _source_worksheet_paths(root, definitions)
    page_blocks = {
        "assembly": _page_blocks(root / "boardwright_resources" / "kibot" / "yaml" / "kibot_out_pdf_assembly.yaml"),
        "fabrication": _page_blocks(root / "boardwright_resources" / "kibot" / "yaml" / "kibot_out_pdf_fabrication.yaml"),
    }
    option_prefixes = {
        "assembly": _option_prefix(root / "boardwright_resources" / "kibot" / "yaml" / "kibot_out_pdf_assembly.yaml"),
        "fabrication": _option_prefix(root / "boardwright_resources" / "kibot" / "yaml" / "kibot_out_pdf_fabrication.yaml"),
    }

    outputs: list[str] = ["kibot:", "  version: 1", "", "outputs:"]
    output_names: list[str] = []
    worksheets: list[Path] = []
    for sheet in sheets:
        blocks = page_blocks.get(sheet.source_kind, ())
        if sheet.source_local_page < 1 or sheet.source_local_page > len(blocks):
            continue
        name = f"pdf_combined_native_{sheet.number:03d}"
        slug = _slug(sheet.title)
        worksheet = worksheet_dir / f"combined_sheet_{sheet.number:03d}.kicad_wks"
        _write_numbered_worksheet(
            source_worksheets[sheet.source_kind],
            worksheet,
            f"SHEET {sheet.number} OF {len(manifest.sheets)}",
            _page_text_variables(root, sheet, definitions),
        )
        worksheets.append(worksheet)
        output_names.append(name)
        prefix = _resolve_placeholders(
            option_prefixes[sheet.source_kind],
            _definition_map_for_kind(sheet.source_kind, definitions),
        )
        prefix = _replace_yaml_option(prefix, "output", f"%f-combined-{sheet.number:03d}-{slug}%I%v.%x")
        prefix = _replace_yaml_option(prefix, "title", f"{sheet.title} DOCUMENT")
        prefix = _replace_yaml_option(
            prefix,
            "sheet_reference_layout",
            "${KIPRJMOD}/" + _posix_path(worksheet.relative_to(root)),
        )
        page_block = _resolve_placeholders(blocks[sheet.source_local_page - 1], _definition_map_for_kind(sheet.source_kind, definitions))
        outputs.extend(
            [
                f"- name: {name}",
                f"  comment: 'Combined review PDF page {sheet.number}: {sheet.title}'",
                "  type: pcb_print",
                "  category: 'Manufacturing/CombinedSources'",
                "  dir: 'Manufacturing/CombinedSources'",
                "  options:",
                _indent(prefix.rstrip(), "    "),
                "    pages:",
                _indent(page_block.strip(), "      "),
                "",
            ]
        )
    yaml_path.write_text("\n".join(outputs).rstrip() + "\n", encoding="utf-8", newline="\n")
    return output_names, worksheets


def _clean_native_combined_outputs(root: Path) -> None:
    _patch_kibot_main_for_native_outputs(root, [])
    yaml_path = root / COMBINED_NATIVE_YAML
    if yaml_path.exists():
        yaml_path.unlink()
    worksheet_dir = root / GENERATED_WORKSHEETS
    if worksheet_dir.is_dir():
        for path in worksheet_dir.glob("combined_sheet_*.kicad_wks"):
            path.unlink()
        schematic_worksheet = root / COMBINED_SCHEMATIC_WORKSHEET
        if schematic_worksheet.exists():
            schematic_worksheet.unlink()


def _prepare_schematic_combined_worksheet(root: Path) -> Path | None:
    source = _schematic_worksheet_path(root)
    if source is None or not source.is_file():
        return None
    target = root / COMBINED_SCHEMATIC_WORKSHEET
    target.parent.mkdir(parents=True, exist_ok=True)
    text = source.read_text(encoding="utf-8")
    text = text.replace("SHEET ${#} OF ${##}", "SHEET ${#} OF ${COMBINED_SHEET_TOTAL}")
    text = text.replace("${#} OF ${##}", "${#} OF ${COMBINED_SHEET_TOTAL}")
    target.write_text(text, encoding="utf-8", newline="\n")
    _patch_schematic_project_worksheet(root, target)
    return target


def _schematic_worksheet_path(root: Path) -> Path | None:
    for path in sorted(root.glob("*.kicad_pro")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        if not isinstance(data, dict):
            continue
        schematic = data.get("schematic")
        if not isinstance(schematic, dict):
            continue
        value = str(schematic.get("page_layout_descr_file") or "").strip()
        if value:
            return _resolve_project_path(root, _normalize_project_worksheet(value))
    definitions = _main_definitions(root)
    return _resolve_project_path(
        root,
        definitions.get("SHEET_WKS", "${KIPRJMOD}/Templates/Boardwright_Template_PCB_GIT_A4.kicad_wks"),
    )


def _normalize_project_worksheet(value: str) -> str:
    normalized = value.replace("\\", "/").strip()
    embed_prefix = "kicad-embed://"
    if normalized.startswith(embed_prefix):
        return (Path("Templates") / normalized.removeprefix(embed_prefix).lstrip("/")).as_posix()
    if normalized.startswith("${KIPRJMOD}/"):
        return normalized.removeprefix("${KIPRJMOD}/")
    return normalized


def _patch_schematic_project_worksheet(root: Path, worksheet: Path) -> None:
    worksheet_ref = "${KIPRJMOD}/" + _posix_path(worksheet.relative_to(root))
    for path in sorted(root.glob("*.kicad_pro")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        if not isinstance(data, dict):
            continue
        schematic = data.setdefault("schematic", {})
        if not isinstance(schematic, dict):
            continue
        schematic["page_layout_descr_file"] = worksheet_ref
        try:
            path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8", newline="\n")
        except PermissionError as exc:
            raise BoardwrightError(
                f"Cannot update schematic worksheet in {path.name}; normalize project file ownership before combined PDF prep."
            ) from exc
        return


def _patch_kibot_main_for_native_outputs(root: Path, output_names: list[str]) -> None:
    path = root / "boardwright_resources" / "kibot" / "yaml" / "kibot_main.yaml"
    if not path.is_file():
        return
    text = path.read_text(encoding="utf-8")
    text = _remove_marked_block(text, MAIN_COMBINED_GROUP_START, MAIN_COMBINED_GROUP_END)
    text = _remove_marked_block(text, MAIN_COMBINED_IMPORT_START, MAIN_COMBINED_IMPORT_END)
    if not output_names:
        text = _remove_group_member(text, "all_group", "combined_native")
        text = _remove_group_member(text, "all_group_k9", "combined_native")
    if output_names:
        group = [MAIN_COMBINED_GROUP_START, "  - name: combined_native", "    outputs:"]
        group.extend(f"      - {name}" for name in output_names)
        group.append(MAIN_COMBINED_GROUP_END)
        text = text.replace("\nimport:\n", "\n" + "\n".join(group) + "\n\nimport:\n", 1)
        text = _add_group_member(text, "all_group", "combined_native")
        text = _add_group_member(text, "all_group_k9", "combined_native")
        imp = "\n".join([
            MAIN_COMBINED_IMPORT_START,
            "  - file: kibot_out_pdf_combined_native.yaml",
            MAIN_COMBINED_IMPORT_END,
        ])
        text = text.replace("\n  # Compress fabrication files", "\n" + imp + "\n\n  # Compress fabrication files", 1)
    path.write_text(text, encoding="utf-8", newline="\n")


def _remove_group_member(text: str, group_name: str, member: str) -> str:
    marker = f"  - name: {group_name}\n    outputs:\n"
    start = text.find(marker)
    if start == -1:
        return text
    insert_at = text.find("\n  - name:", start + len(marker))
    if insert_at == -1:
        insert_at = text.find("\nimport:", start)
    if insert_at == -1:
        insert_at = len(text)
    block = text[start:insert_at]
    line_pattern = re.compile(rf"^\s*- {re.escape(member)}\n?", re.MULTILINE)
    return text[:start] + line_pattern.sub("", block) + text[insert_at:]


def _add_group_member(text: str, group_name: str, member: str) -> str:
    marker = f"  - name: {group_name}\n    outputs:\n"
    start = text.find(marker)
    if start == -1:
        return text
    insert_at = text.find("\n  - name:", start + len(marker))
    if insert_at == -1:
        insert_at = text.find("\nimport:", start)
    block = text[start:insert_at]
    line = f"      - {member}"
    if line in block:
        return text
    return text[:insert_at] + "\n" + line + text[insert_at:]


def _remove_marked_block(text: str, start_marker: str, end_marker: str) -> str:
    pattern = re.compile(rf"\n?{re.escape(start_marker)}.*?{re.escape(end_marker)}\n?", re.DOTALL)
    return pattern.sub("\n", text)


def _source_worksheet_paths(root: Path, definitions: dict[str, str]) -> dict[str, Path]:
    raw = definitions.get("SHEET_WKS", "${KIPRJMOD}/Templates/Boardwright_Template_PCB_GIT_A4.kicad_wks")
    path = _resolve_project_path(root, raw)
    return {"assembly": path, "fabrication": path}


def _resolve_project_path(root: Path, value: str) -> Path:
    value = value.strip().strip("'").strip('"').replace("${KIPRJMOD}", str(root).replace("\\", "/"))
    path = Path(value)
    return path if path.is_absolute() else root / path


def _write_numbered_worksheet(
    source: Path,
    target: Path,
    number_text: str,
    text_variables: dict[str, str] | None = None,
) -> None:
    text = source.read_text(encoding="utf-8")
    text = text.replace("SHEET ${#} OF ${##}", number_text)
    text = text.replace("${#} OF ${##}", number_text.removeprefix("SHEET "))
    text = text.replace("SHEET ${#} OF ${COMBINED_SHEET_TOTAL}", number_text)
    text = text.replace("${#} OF ${COMBINED_SHEET_TOTAL}", number_text.removeprefix("SHEET "))
    for key, value in (text_variables or {}).items():
        text = text.replace("${" + key + "}", value)
    target.write_text(text, encoding="utf-8", newline="\n")


def _page_text_variables(root: Path, sheet: CombinedSheet, definitions: dict[str, str]) -> dict[str, str]:
    values = dict(_document_text_variables(root, sheet.source_kind, definitions))
    if sheet.title:
        values["DRAWING_TITLE"] = sheet.title.upper()
    return values


def _main_definitions(root: Path) -> dict[str, str]:
    path = root / "boardwright_resources" / "kibot" / "yaml" / "kibot_main.yaml"
    text = path.read_text(encoding="utf-8")
    marker = "\ndefinitions:\n"
    index = text.rfind(marker)
    values: dict[str, str] = {}
    if index == -1:
        return values
    for raw in text[index + len(marker):].splitlines():
        match = re.match(r"\s{2}([A-Z0-9_]+):\s*(.*)$", raw)
        if match:
            values[match.group(1)] = match.group(2).strip().strip("'")
    return values


def _document_text_variables(root: Path, kind: str, definitions: dict[str, str]) -> dict[str, str]:
    generated = {
        "assembly": root / "boardwright_resources" / "kibot" / "yaml" / "kibot_document_assembly.generated.yaml",
        "fabrication": root / "boardwright_resources" / "kibot" / "yaml" / "kibot_document_fabrication.generated.yaml",
    }.get(kind)
    values = _definitions_from_yaml(generated) if generated is not None and generated.is_file() else {}
    if values:
        return values
    if kind == "assembly":
        return {
            "DOCUMENT_TYPE": "ASSEMBLY",
            "DRAWING_TITLE": "ASSEMBLY DRAWING",
            "DRAWING_NUMBER": definitions.get("PCBA_NAME", definitions.get("DRAWING_NUMBER", "")),
        }
    return {
        "DOCUMENT_TYPE": "FABRICATION",
        "DRAWING_TITLE": "FABRICATION DRAWING",
        "DRAWING_NUMBER": definitions.get("PCB_NAME", definitions.get("DRAWING_NUMBER", "")),
    }


def _definitions_from_yaml(path: Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    marker = "\ndefinitions:\n"
    index = text.rfind(marker)
    if index == -1:
        return {}
    values: dict[str, str] = {}
    for raw in text[index + len(marker):].splitlines():
        match = re.match(r"\s{2}([A-Z0-9_]+):\s*(.*)$", raw)
        if match:
            values[match.group(1)] = match.group(2).strip().strip("'")
    return values


