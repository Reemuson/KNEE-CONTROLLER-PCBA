def build_combined_pdf_plan(config, root: Path | None = None) -> CombinedPdfPlan:
    project_root = (root or config.root).resolve()
    outputs = getattr(config, "output_settings", {}) or {}
    enabled = _as_bool(outputs.get("combined_review_pdf", False))
    output_path = project_root / "Manufacturing" / "boardwright-combined.pdf"

    return CombinedPdfPlan(
        enabled=enabled,
        output_path=output_path,
        inputs=tuple(_discover_inputs(project_root, output_path)),
        toc_enabled=True,
        page_numbers_enabled=True,
    )


def build_combined_sheet_manifest(config, root: Path | None = None) -> CombinedSheetManifest:
    project_root = (root or config.root).resolve()
    outputs = getattr(config, "output_settings", {}) or {}
    enabled = _as_bool(outputs.get("combined_review_pdf", False))
    sheets = tuple(_combined_sheets(project_root)) if enabled else ()
    return CombinedSheetManifest(enabled=enabled, sheets=sheets, path=project_root / COMBINED_SHEET_TITLES)


def write_combined_sheet_manifest(config, root: Path | None = None) -> CombinedSheetManifest:
    manifest = build_combined_sheet_manifest(config, root)
    if not manifest.enabled:
        if manifest.path.exists():
            manifest.path.unlink()
        return manifest

    manifest.path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by Boardwright. Used by KiCad/KiBot text variables for the native combined review PDF."]
    lines.append(f"COMBINED_SHEET_TOTAL={len(manifest.sheets)}")
    for sheet in manifest.sheets[:MAX_COMBINED_TOC_ENTRIES]:
        lines.append(f"SHEET_NAME_{sheet.number}={sheet.title}")
        lines.append(f"SHEET_SECTION_{sheet.number}={sheet.section}")
        lines.append(f"SHEET_SOURCE_KIND_{sheet.number}={sheet.source_kind}")
        lines.append(f"SHEET_SOURCE_PAGE_{sheet.number}={sheet.source_local_page}")
    manifest.path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return manifest


def write_combined_pdf(config, root: Path | None = None) -> CombinedPdfPlan:
    plan = build_combined_pdf_plan(config, root)
    if not plan.enabled:
        return plan
    if not plan.inputs:
        raise BoardwrightError("Combined PDF is enabled, but no source PDFs were found.")

    try:
        from pypdf import PdfReader, PdfWriter
    except ImportError as exc:
        raise BoardwrightError("Combined PDF output requires the `pypdf` Python package.") from exc

    project_root = (root or config.root).resolve()
    writer = PdfWriter()
    page_index = 0
    bookmark_manifest = _read_combined_sheet_manifest(project_root)
    for item in plan.inputs:
        reader = PdfReader(str(item.path))
        if len(reader.pages) == 0:
            continue
        section_start = page_index
        for page in reader.pages:
            writer.add_page(page)
            page_index += 1
        if not bookmark_manifest:
            parent = writer.add_outline_item(item.title, section_start)
            copied = _copy_source_outline(writer, reader, parent, section_start)
            if not copied:
                titles = _titles_for_input(project_root, item, len(reader.pages))
                for index, _page in enumerate(reader.pages):
                    title = _page_title(item.title, titles, index)
                    writer.add_outline_item(title, section_start + index, parent=parent)

    if page_index == 0:
        raise BoardwrightError("Combined PDF source files did not contain any pages.")
    if bookmark_manifest and page_index >= len(bookmark_manifest):
        for sheet in bookmark_manifest:
            writer.add_outline_item(sheet.title, sheet.number - 1)

    plan.output_path.parent.mkdir(parents=True, exist_ok=True)
    with plan.output_path.open("wb") as handle:
        writer.write(handle)
    return plan


def format_combined_pdf_summary(plan: CombinedPdfPlan) -> str:
    if not plan.enabled:
        return "Combined PDF: disabled."
    if not plan.inputs:
        return f"Combined PDF: enabled, no source PDFs found for {plan.output_path.name}."
    inputs = ", ".join(f"{item.title}={_display_path(item.path, plan.output_path.parent)}" for item in plan.inputs)
    return f"Combined PDF: wrote {_display_path(plan.output_path, plan.output_path.parent)} from {inputs}."


def format_combined_sheet_manifest_summary(manifest: CombinedSheetManifest) -> str:
    if not manifest.enabled:
        return "Combined PDF native contents: disabled."
    return f"Combined PDF native contents: wrote {_display_path(manifest.path, manifest.path.parent)} with {len(manifest.sheets)} sheet title(s)."


def read_combined_sheet_title(root: Path, page_number: int) -> str | None:
    values = _read_env(root / COMBINED_SHEET_TITLES)
    return values.get(f"SHEET_NAME_{page_number}")


def read_combined_sheet_total(root: Path) -> int | None:
    values = _read_env(root / COMBINED_SHEET_TITLES)
    value = values.get("COMBINED_SHEET_TOTAL")
    if value is None:
        return None
    try:
        return int(value)
    except ValueError:
        return None


def native_pcb_sheets(manifest: CombinedSheetManifest) -> tuple[CombinedSheet, ...]:
    return tuple(sheet for sheet in manifest.sheets if sheet.source_kind in {"assembly", "fabrication"})



def prepare_native_combined_outputs(config, root: Path | None = None) -> NativeCombinedOutputResult:
    project_root = (root or config.root).resolve()
    manifest = write_combined_sheet_manifest(config, project_root)
    if not manifest.enabled:
        _clean_native_combined_outputs(project_root)
        return NativeCombinedOutputResult(manifest, (), (), project_root / COMBINED_NATIVE_YAML)

    _prepare_schematic_combined_worksheet(project_root)
    output_names, worksheets = _write_native_pcb_outputs(project_root, manifest)
    _patch_kibot_main_for_native_outputs(project_root, output_names)
    return NativeCombinedOutputResult(
        manifest=manifest,
        output_names=tuple(output_names),
        worksheets=tuple(worksheets),
        yaml_path=project_root / COMBINED_NATIVE_YAML,
    )


